const language = localStorage.getItem('yt-language') || 'system';
void i18n.use(initReactI18next).init({
  resources: { 'zh-CN': { translation: zh }, en: { translation: en } },
  lng: language === 'system' ? (navigator.language.startsWith('zh') ? 'zh-CN' : 'en') : language,
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
});
export function applyLanguage(language: string) {
  localStorage.setItem('yt-language', language);
  void i18n.changeLanguage(
    language === 'system' ? (navigator.language.startsWith('zh') ? 'zh-CN' : 'en') : language,
  );
}
export default i18n;
